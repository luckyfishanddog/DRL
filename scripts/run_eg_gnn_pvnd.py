def training_layouts():
    source=ROOT/'data/weld_layout/train.jsonl'
    rows=[json.loads(line) for line in source.read_text(encoding='utf-8').splitlines()]
    ordered=sorted(rows,key=lambda r:(len(r['parents']),r['layout_id']))
    selected=[ordered[round(i*(len(ordered)-1)/19)] for i in range(20)]
    return [(r['layout_id'],tuple(ParentWeld(p['parent_id'],tuple(p['start']),tuple(p['end']))
            for p in r['parents']),'holdout' if i in HOLDOUT_INDICES else 'fit')
            for i,r in enumerate(selected)]

def records():
    if not DATA.exists():return []
    with gzip.open(DATA,'rt',encoding='utf-8') as stream:
        return [json.loads(line) for line in stream if line.strip()]

class VNDObserver:
    def __init__(self,interval=8.):
        self.interval=interval
        self.buckets=set()
        self.groups=[]
        self.pending=None
    def begin(self,workspace,selected,elapsed,index):
        bucket=int(elapsed//self.interval)
        if bucket in self.buckets or elapsed>=BUDGET:return None
        self.buckets.add(bucket)
        self.pending=dict(elapsed_s=elapsed,individual_index=index,selected=selected.tolist())
        return hga.make_vnd_trace(2*len(workspace.parents),states=4,per_move=24)
    def end(self,workspace,selected,trace):
        nodes,bits,lengths,actions,counts,passes=trace
        for slot,p in enumerate(passes):
            if not p:continue
            aa=[a.tolist() for family in actions[slot] for a in family if a[0]>=0]
            if not aa:continue
            aa.sort(key=lambda a:a[7])
            self.groups.append(dict(self.pending,pass_number=int(p),
                routes=[nodes[slot,r,:lengths[slot,r]].tolist() for r in range(4)],
                directions=[bits[slot,r,:lengths[slot,r]].tolist() for r in range(4)],
                actions=aa,visited_legal_per_move=counts[slot].tolist()))

def worker_init():
    global WARM_SECONDS
    set_num_threads(1);torch.set_num_threads(1)
    # Compile both observed and ordinary paths, using a subset of TRAIN solely
    # for compilation. No labels or B32 are generated by this warm-up.
    _,parents,_=training_layouts()[1]
    parents=parents[:8]
    settings=replace(hga.AdaptedHGAConfig(),vnd_objective='ROUTE_CYCLE',max_iterations=1)
    started=time.perf_counter()
    observer=VNDObserver()
    hga.run_adapted_hga_v2(parents,CONFIG,settings,seed=SEED,time_limit=math.inf,
        checkpoints=(),certify=False,candidate_evaluator=priority_schedule,vnd_observer=observer)
    WARM_SECONDS=time.perf_counter()-started
    print('EG_WARM',os.getpid(),round(WARM_SECONDS,3),flush=True)

def materialize(routes,bits,action):
    move,_,_,ru,iu,rv,iv=(int(x) for x in action[:7])
    a,b=hga._move_segments(routes,move,ru,iu,rv,iv)
    result,directions=list(routes),list(bits)
    result[ru]=hga._materialize_segments(a,routes)
    directions[ru]=hga._materialize_directions(a,bits)
    if move!=4:
        result[rv]=hga._materialize_segments(b,routes)
        directions[rv]=hga._materialize_directions(b,bits)
    return result,directions

def label_observations(workspace,raw_groups,name):
    cache={}
    state_keys=set()
    groups=[]
    native_calls=cache_hits=0
    native_seconds=0.
    def evaluate(routes,bits,selected):
        nonlocal native_calls,cache_hits,native_seconds
        key=(tuple(selected),hga._oriented_identity(routes,bits))
        if key in cache:
            cache_hits+=1
            return cache[key],True
        started=time.perf_counter()
        value,_,_,_=_priority_arrays(routes,workspace.travel,workspace.processing,
            workspace.points,workspace.parameters,bits)
        elapsed=time.perf_counter()-started
        native_calls+=1;native_seconds+=elapsed
        result=dict(native_cmax_s=float(value) if math.isfinite(value) else None,
            native_status='FEASIBLE' if math.isfinite(value) else 'NUMERIC_FAILURE' if math.isnan(value) else 'NATIVE_REJECTED',
            native_eval_s=elapsed)
        cache[key]=result
        return result,False
    for index,raw in enumerate(raw_groups):
        rr=[np.array(r,np.int64) for r in raw['routes']]
        dd=[np.array(d,np.int64) for d in raw['directions']]
        key=(tuple(raw['selected']),hga._oriented_identity(rr,dd))
        if key in state_keys:continue
        state_keys.add(key)
        before,before_hit=evaluate(rr,dd,raw['selected'])
        candidates=[]
        for action in raw['actions']:
            started=time.perf_counter()
            nr,nd=materialize(rr,dd,action)
            materialize_s=time.perf_counter()-started
            after,hit=evaluate(nr,nd,raw['selected'])
            current,value=before['native_cmax_s'],after['native_cmax_s']
            known=before['native_status']!='NUMERIC_FAILURE' and after['native_status']!='NUMERIC_FAILURE'
            positive=known and value is not None and (current is None or value<current-1.e-8)
            candidates.append(dict(action=action,**after,cache_hit=hit,materialize_s=materialize_s,
                label_known=known,positive=bool(positive),
                improvement_s=current-value if current is not None and value is not None else None,
                teacher_accepted=bool(action[8])))
        group={k:v for k,v in raw.items() if k!='actions'}
        group.update(current_native=before,current_cache_hit=before_hit,candidates=candidates)
        groups.append(group)
        if index%8==0:print('EG_LABEL',name,index+1,'/',len(raw_groups),native_calls,flush=True)
    return groups,dict(label_native_calls=native_calls,label_cache_hits=cache_hits,
        label_native_s=native_seconds,raw_states=len(raw_groups),unique_states=len(groups))

def teacher_job(entry):
    name,parents,role=entry
    print('EG_TEACHER_START',name,len(parents),role,flush=True)
    observer=VNDObserver()
    settings=replace(hga.AdaptedHGAConfig(),vnd_objective='ROUTE_CYCLE')
    started=time.perf_counter()
    result=hga.run_adapted_hga_v2(parents,CONFIG,settings,seed=SEED,time_limit=BUDGET,
        checkpoints=(),certify=False,candidate_evaluator=priority_schedule,vnd_observer=observer)
    teacher_seconds=time.perf_counter()-started
    print('EG_TEACHER_DONE',name,result.iterations,round(teacher_seconds,3),len(observer.groups),flush=True)
    workspace=hga._HGAWorkspace(parents,CONFIG,FORMAL_SCOPE_V2)
    labeling_started=time.perf_counter()
    groups,counts=label_observations(workspace,observer.groups,name)
    row=dict(layout_id=name,parent_count=len(parents),role=role,seed=SEED,
        parents=[dict(parent_id=p.parent_id,start=p.start,end=p.end) for p in parents],
        teacher_objective='ROUTE_CYCLE',label_objective='NATIVE_COORDINATED_FIXED_DIRECTIONS',
        sampling='one VND per eight-second window; first three and rolling final passes; first 24 legal visits per M1-M6 plus actual accepted action',
        teacher_runtime_s=teacher_seconds,teacher_iterations=result.iterations,
        teacher_termination=result.termination_reason,teacher_accounting=result.accounting,
        labeling_runtime_s=time.perf_counter()-labeling_started,worker_warm_s=WARM_SECONDS,
        b32_calls=0,groups=groups,**counts)
    print('EG_TEACHER_RESULT',json.dumps(dict(layout_id=name,parent_count=len(parents),role=role,
        states=len(groups),actions=sum(len(g['candidates']) for g in groups),
        positives=sum(c['positive'] for g in groups for c in g['candidates']),
        accepted=sum(c['teacher_accepted'] for g in groups for c in g['candidates']),
        teacher_s=teacher_seconds,labeling_s=row['labeling_runtime_s'],**counts)),flush=True)
    return row

def collect(workers):
    existing=records()
    done={r['layout_id'] for r in existing}
    jobs=[entry for entry in training_layouts() if entry[0] not in done]
    print('EG_COLLECT',len(done),'completed',len(jobs),'remaining',flush=True)
    if not jobs:return existing
    started=time.perf_counter()
    with ProcessPoolExecutor(max_workers=workers,initializer=worker_init) as pool:
        futures={pool.submit(teacher_job,entry):entry[0] for entry in jobs}
        for future in as_completed(futures):
            row=future.result()
            # Concatenated gzip members allow ordinary append without replacing
            # existing layout records or creating temporary/management files.
            with gzip.open(DATA,'at',encoding='utf-8',compresslevel=6) as stream:
                stream.write(json.dumps(row,ensure_ascii=False,allow_nan=False)+'\n')
            existing.append(row)
            print('EG_SAVED',row['layout_id'],len(existing),'/ 20',flush=True)
    print('EG_COLLECTION_WALL_S',time.perf_counter()-started,flush=True)
    return existing

def workspace_for(row):
    parents=tuple(ParentWeld(p['parent_id'],tuple(p['start']),tuple(p['end'])) for p in row['parents'])
    return hga._HGAWorkspace(parents,CONFIG,FORMAL_SCOPE_V2)

def inputs_for(workspace,group):
    rr=[np.array(r,np.int64) for r in group['routes']]
    dd=[np.array(d,np.int64) for d in group['directions']]
    actions=np.array([c['action'] for c in group['candidates']],np.int64)
    return hga_vnd_inputs(workspace,rr,dd,actions,group['current_native']['native_cmax_s'])

def prepare(source):
    samples=[]
    for row in source:
        workspace=workspace_for(row)
        for raw in row['groups']:
            candidates=[c for c in raw['candidates'] if c['label_known']]
            if not candidates:continue
            group=dict(raw,candidates=candidates)
            inputs=inputs_for(workspace,group)
            samples.append(dict(layout_id=row['layout_id'],parent_count=row['parent_count'],role=row['role'],
                inputs=inputs,group=group,positive=torch.tensor([c['positive'] for c in candidates],dtype=torch.float32),
                logcost=torch.tensor([math.log(max(1.e-9,c['native_eval_s'])) for c in candidates],dtype=torch.float32)))
    return samples

def ranking_loss(scores,positive,candidates):
    good=torch.where(positive>0)[0];bad=torch.where(positive==0)[0]
    loss=scores.sum()*0
    if len(good) and len(bad):
        a=good[torch.randint(len(good),(min(256,len(good)*len(bad)),))]
        b=bad[torch.randint(len(bad),(len(a),))]
        loss=F.softplus(scores[b]-scores[a]).mean()
    # Preserve genuine Cmax ordering among the actually evaluated feasible
    # actions as well; an accepted flag or proxy value is never a label.
    feasible=torch.tensor([c['native_cmax_s'] is not None for c in candidates])
    values=torch.tensor([c['native_cmax_s'] if c['native_cmax_s'] is not None else 0. for c in candidates],dtype=torch.float64)
    if int(feasible.sum())>1:
        a=torch.randint(len(scores),(128,));b=torch.randint(len(scores),(128,))
        valid=feasible[a]&feasible[b]&(values[a]<values[b]-1.e-8)
        if bool(valid.any()):
            loss=loss+.25*F.softplus(scores[b[valid]]-scores[a[valid]]).mean()
    return loss

def order_metrics(candidates,priority):
    positive=np.array([c['positive'] for c in candidates],bool)
    original=np.arange(len(candidates))
    ordered=np.argsort(-priority,kind='stable')
    shuffled=original.copy()
    np.random.default_rng(SEED+len(candidates)).shuffle(shuffled)
    costs=np.array([c['native_eval_s']+c['materialize_s'] for c in candidates])
    def until(order):
        indices=np.flatnonzero(positive[order])
        n=int(indices[0])+1 if len(indices) else len(order)
        return n,float(costs[order[:n]].sum())
    first,gnn,randomized=until(original),until(ordered),until(shuffled)
    good=priority[positive];bad=priority[~positive]
    auc=float(((good[:,None]>bad).astype(float)+.5*(good[:,None]==bad)).mean()) if len(good) and len(bad) else None
    return dict(actions=len(candidates),positives=int(positive.sum()),pairwise_accuracy=auc,
        original_evals=first[0],gnn_evals=gnn[0],random_evals=randomized[0],
        original_service_s=first[1],gnn_service_s=gnn[1],has_improvement=bool(positive.any()),
        top1_improves=bool(positive[ordered[0]]),original_top1_improves=bool(positive[0]))

def offline(model,samples,cost_mean,cost_std,source):
    model.eval()
    by_name={r['layout_id']:r for r in source}
    workspaces={}
    details=[]
    with torch.inference_mode():
        for sample in samples:
            if sample['role']!='holdout':continue
            name=sample['layout_id']
            if name not in workspaces:workspaces[name]=workspace_for(by_name[name])
            # Measure feature building + graph encoder + all action scores.
            elapsed=[];neural=[];prediction=None
            for repeat in range(3):
                started=time.perf_counter()
                inputs=inputs_for(workspaces[name],sample['group'])
                encoded=time.perf_counter()
                prediction=model(inputs)
                model_completed=time.perf_counter()
                predicted_logcost=cost_mean+cost_std*prediction[:,1]
                priority=(F.logsigmoid(prediction[:,0])-predicted_logcost).numpy()
                np.argsort(-priority,kind='stable')
                completed=time.perf_counter()
                elapsed.append(completed-started);neural.append(model_completed-encoded)
            metric=order_metrics(sample['group']['candidates'],priority)
            raw_metric=order_metrics(sample['group']['candidates'],prediction[:,0].numpy())
            actual_logcost=sample['logcost']
            metric.update(raw_pairwise_accuracy=raw_metric['pairwise_accuracy'],
                cost_log_mae=float((predicted_logcost-actual_logcost).abs().mean()),
                constant_cost_log_mae=float((cost_mean-actual_logcost).abs().mean()))
            positive=np.array([c['positive'] for c in sample['group']['candidates']],bool)
            ranked=np.argsort(-priority,kind='stable')
            metric['topk_improves']={str(k):bool(positive[ranked[:k]].any()) for k in (1,4,8,16)}
            metric.update(layout_id=name,parent_count=sample['parent_count'],
                current_native_feasible=sample['group']['current_native']['native_cmax_s'] is not None,
                inference_s=median(elapsed),neural_s=median(neural),
                net_estimated_s_saved=metric['original_service_s']-metric['gnn_service_s']-median(elapsed))
            details.append(metric)
    layout_rows=[]
    for name in sorted(workspaces,key=lambda name:by_name[name]['parent_count']):
        subset=[d for d in details if d['layout_id']==name]
        positive=[d for d in subset if d['has_improvement']]
        auc=[d['pairwise_accuracy'] for d in subset if d['pairwise_accuracy'] is not None]
        layout_rows.append(dict(layout_id=name,parent_count=by_name[name]['parent_count'],groups=len(subset),
            improvement_groups=len(positive),pairwise_accuracy=mean(auc) if auc else None,
            original_first_mean=mean(d['original_evals'] for d in positive) if positive else None,
            gnn_first_mean=mean(d['gnn_evals'] for d in positive) if positive else None,
            random_first_mean=mean(d['random_evals'] for d in positive) if positive else None,
            total_original_evals=sum(d['original_evals'] for d in subset),
            total_gnn_evals=sum(d['gnn_evals'] for d in subset),
            raw_pairwise_accuracy=mean(d['raw_pairwise_accuracy'] for d in subset if d['raw_pairwise_accuracy'] is not None) if auc else None,
            cost_log_mae=mean(d['cost_log_mae'] for d in subset),constant_cost_log_mae=mean(d['constant_cost_log_mae'] for d in subset),
            full_inference_median_ms=1000*median(d['inference_s'] for d in subset),
            neural_median_ms=1000*median(d['neural_s'] for d in subset),
            recorded_original_service_s=sum(d['original_service_s'] for d in subset),
            estimated_gnn_service_plus_inference_s=sum(d['gnn_service_s']+d['inference_s'] for d in subset),
            estimated_net_s_saved=sum(d['net_estimated_s_saved'] for d in subset)))
    positive=[d for d in details if d['has_improvement']]
    auc=[d['pairwise_accuracy'] for d in details if d['pairwise_accuracy'] is not None]
    summary=dict(heldout_layouts=len(layout_rows),groups=len(details),improvement_groups=len(positive),
        pairwise_accuracy=mean(auc) if auc else None,
        original_first_mean=mean(d['original_evals'] for d in positive) if positive else None,
        gnn_first_mean=mean(d['gnn_evals'] for d in positive) if positive else None,
        random_first_mean=mean(d['random_evals'] for d in positive) if positive else None,
        original_evals=sum(d['original_evals'] for d in details),gnn_evals=sum(d['gnn_evals'] for d in details),
        raw_pairwise_accuracy=mean(d['raw_pairwise_accuracy'] for d in details if d['raw_pairwise_accuracy'] is not None) if auc else None,
        cost_log_mae=mean(d['cost_log_mae'] for d in details),constant_cost_log_mae=mean(d['constant_cost_log_mae'] for d in details),
        topk_improvement_recall={str(k):mean(d['topk_improves'][str(k)] for d in positive) if positive else None for k in (1,4,8,16)},
        full_inference_median_ms=1000*median(d['inference_s'] for d in details),
        neural_median_ms=1000*median(d['neural_s'] for d in details),
        original_recorded_service_s=sum(d['original_service_s'] for d in details),
        estimated_gnn_service_plus_inference_s=sum(d['gnn_service_s']+d['inference_s'] for d in details))
    summary['estimated_net_s_saved']=summary['original_recorded_service_s']-summary['estimated_gnn_service_plus_inference_s']
    conditions=dict(ranks_improvements=summary['pairwise_accuracy'] is not None and summary['pairwise_accuracy']>.5,
        all_scales_rank=all(r['pairwise_accuracy'] is not None and r['pairwise_accuracy']>.5 for r in layout_rows),
        fewer_evaluations=summary['gnn_first_mean'] is not None and summary['gnn_first_mean']<summary['original_first_mean'],
        pays_for_inference=summary['estimated_net_s_saved']>0)
    summary['conditions']=conditions
    summary['worth_stage_two']=all(conditions.values())
    print('EG_OFFLINE_SUMMARY',json.dumps(summary),flush=True)
    for row in layout_rows:print('EG_OFFLINE_LAYOUT',json.dumps(row),flush=True)
    return dict(summary=summary,layouts=layout_rows,groups=details,
        scope='only actually observed and native-evaluated candidate pools; full feature/scoring/priority/sort overhead; recorded service-time estimate, not a full search speedup')

def fit():
    torch.set_num_threads(1);set_num_threads(1)
    if MODEL.exists():
        checkpoint=torch.load(MODEL,map_location='cpu',weights_only=False)
        current=checkpoint.get('offline_full_decision',checkpoint['offline'])
        print('EG_RETAINED_MODEL',json.dumps(current['summary']),flush=True)
        return checkpoint
    source=records()
    expected={name for name,_,_ in training_layouts()}
    if {r['layout_id'] for r in source}!=expected:raise ValueError('collect the twenty TRAIN layouts first')
    random.seed(SEED);np.random.seed(SEED);torch.manual_seed(SEED)
    started=time.perf_counter()
    samples=prepare(source)
    train=[s for s in samples if s['role']=='fit']
    logcost=torch.cat([s['logcost'] for s in train])
    cost_mean=float(logcost.mean());cost_std=max(.1,float(logcost.std()))
    positive=torch.cat([s['positive'] for s in train])
    pos_weight=torch.tensor(min(20.,max(1.,float((1-positive).sum()/positive.sum().clamp_min(1)))))
    model=HGAVNDCandidateGNN()
    optimizer=torch.optim.AdamW(model.parameters(),lr=.001,weight_decay=1.e-5)
    history=[]
    print('EG_FIT_START','states',len(train),'holdout',len(samples)-len(train),
        'parameters',sum(p.numel() for p in model.parameters()),flush=True)
    for epoch in range(EPOCHS):
        model.train()
        order=list(range(len(train)));random.Random(SEED+epoch).shuffle(order)
        losses=[]
        for begin in range(0,len(order),8):
            batch=[train[i] for i in order[begin:begin+8]]
            inputs=batch_hga_vnd_inputs([s['inputs'] for s in batch])
            prediction=model(inputs)
            targets=torch.cat([s['positive'] for s in batch])
            costs=(torch.cat([s['logcost'] for s in batch])-cost_mean)/cost_std
            cursor=0;pair=prediction.sum()*0
            for sample in batch:
                count=len(sample['positive'])
                pair=pair+ranking_loss(prediction[cursor:cursor+count,0],sample['positive'],sample['group']['candidates'])
                cursor+=count
            loss=pair/len(batch)+.25*F.binary_cross_entropy_with_logits(prediction[:,0],targets,pos_weight=pos_weight)+.1*F.smooth_l1_loss(prediction[:,1],costs)
            optimizer.zero_grad();loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(),5.)
            optimizer.step();losses.append(float(loss.detach()))
        history.append(dict(epoch=epoch+1,loss=mean(losses)))
        print('EG_FIT_EPOCH',epoch+1,round(history[-1]['loss'],6),flush=True)
    training_s=time.perf_counter()-started
    result=offline(model,samples,cost_mean,cost_std,source)
    checkpoint=dict(state_dict=model.state_dict(),seed=SEED,epochs=EPOCHS,hidden_dim=32,heads=2,
        cost_mean=cost_mean,cost_std=cost_std,history=history,training_s=training_s,
        train_layouts=[name for name,_,role in training_layouts() if role=='fit'],
        heldout_train_layouts=[name for name,_,role in training_layouts() if role=='holdout'],
        teacher_source=str(DATA),offline=result,parameters=sum(p.numel() for p in model.parameters()),
        model_selection='fixed final epoch; no held-out/VALIDATION/TEST model selection')
    with MODEL.open('xb') as stream:torch.save(checkpoint,stream)
    print('EG_MODEL_SAVED',str(MODEL),'seconds',training_s,flush=True)
    return checkpoint

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stage',choices=('collect','fit','all','summary'))
    parser.add_argument('--workers',type=int,default=4)
    args=parser.parse_args()
    if args.workers<1:parser.error('--workers must be positive')
    if args.stage in ('collect','all'):collect(args.workers)
    if args.stage in ('fit','all'):fit()
    if args.stage=='summary':
        source=records()
        print('EG_DATA_SUMMARY',len(source),sum(len(r['groups']) for r in source))
        if MODEL.exists():
            checkpoint=torch.load(MODEL,map_location='cpu',weights_only=False)
            current=checkpoint.get('offline_full_decision',checkpoint['offline'])
            print('EG_OFFLINE_SUMMARY',json.dumps(current['summary']))
            for row in current['layouts']:print('EG_OFFLINE_LAYOUT',json.dumps(row))

if __name__=='__main__':main()
